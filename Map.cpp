//  Map.cpp  --  CASTLE: Hall -> Solar -> Dungeon
//
//  CELL ID CONVENTION (kept from the original file):
//    <region>_<x two digits>_<y two digits>     e.g. h_04_45, s_12_07, d_50_18
//    region : h = Hall, s = Solar, d = Dungeon
//    x : 1..50 (west -> east),   y : 1..35 (north -> south)
//
//  LAYOUT
//    Hall    : enter WEST (h_01_18), corridor runs EAST, staircase at h_50_18
//              climbs NORTH into the Solar (s_50_18).
//    Solar   : enter EAST (s_50_18), corridor runs WEST, tunnel at s_01_18
//              descends SOUTH into the Dungeon (d_01_18).
//    Dungeon : enter WEST (d_01_18), corridor runs EAST, exit at d_50_18.
//
//  KEY CHAIN (5 keys + 5 gates PER FLOOR, each gate needs the previous key)
//    hkey1 (Hall, shallow)   -> hlock1  (spine gate 1)
//    hkey2 (past lock1)      -> hlock2  (spine gate 2)
//    hkey3 (past lock2)      -> hlock3  (spine gate 3)
//    hkey4 (past lock3)      -> hlock4  (VAULT side gate, guards hkey5)
//    hkey5 (inside the vault)-> hlock5  (final spine gate -> exit)
//    ...identical chain for s* (Solar) and d* (Dungeon).
//    lockedBy[dir] stores the KEY name (e.g. "hkey1") so the obvious check
//    `if (player has lockedBy[dir]) open;` works. The gate LABEL (hlock1)
//    lives in the cell name + its directional description. If your engine
//    compares against the label instead, swap the 3rd arg of the locked
//    connect() calls to "hlock1"/"hlock2"/... (5 per floor).
//
//  Every cell carries four directional descriptions (north/south/east/west).
//  Dead-end rooms describe their walls with flavour, and a room that holds a
//  key names it in one of its wall directions (e.g. "...behind it rests the
//  hkey2!").
//
//  ENTRY POINT: call buildMap() exactly once at startup.
// ============================================================================

